use std::path::PathBuf;
use crate::error::Result;
use crate::parser::ast::*;
use crate::codegen::generator::{CodeGenerator, GeneratedFile, GeneratorOptions};

pub struct TypeScriptGenerator;

impl TypeScriptGenerator {
    pub fn new() -> Self {
        Self
    }

    fn map_primitive_type(prim: &PrimitiveType) -> &'static str {
        match prim {
            PrimitiveType::Bool => "boolean",
            PrimitiveType::U8 | PrimitiveType::U16 | PrimitiveType::U32 |
            PrimitiveType::I8 | PrimitiveType::I16 | PrimitiveType::I32 |
            PrimitiveType::F32 | PrimitiveType::F64 => "number",
            PrimitiveType::U64 | PrimitiveType::I64 | PrimitiveType::Timestamp => "bigint",
            PrimitiveType::String | PrimitiveType::Uuid => "string",
            PrimitiveType::Bytes => "Uint8Array",
        }
    }

    fn map_type(&self, ty: &FieldType) -> String {
        match ty {
            FieldType::Primitive(p) => Self::map_primitive_type(p).to_string(),
            FieldType::List(inner) => format!("Array<{}>", self.map_type(inner)),
            FieldType::Map(k, v) => format!("Map<{}, {}>", self.map_type(k), self.map_type(v)),
            FieldType::Option(inner) => format!("{} | null | undefined", self.map_type(inner)),
            FieldType::Result { ok, err } => format!("{{ ok: true; value: {} }} | {{ ok: false; error: {} }}", self.map_type(ok), self.map_type(err)),
            FieldType::Custom(name) => name.clone(),
        }
    }
}

impl CodeGenerator for TypeScriptGenerator {
    fn generate(&self, schema: &Schema, options: &GeneratorOptions) -> Result<Vec<GeneratedFile>> {
        let mut out = String::new();

        out.push_str("/**\n * Code generated by synapse-rpc-compiler. DO NOT EDIT.\n */\n\n");
        out.push_str("/* eslint-disable */\n\n");

        // Helper runtime types & utilities
        out.push_str("// --- Synapse Runtime Types ---\n");
        out.push_str("export const SYNAPSE_MAGIC = 0x53594E50;\n");
        out.push_str("export const SYNAPSE_VERSION = 1;\n\n");
        out.push_str("export enum FrameType {\n");
        out.push_str("  Handshake = 1,\n");
        out.push_str("  CallRequest = 2,\n");
        out.push_str("  CallResponse = 3,\n");
        out.push_str("  StreamData = 4,\n");
        out.push_str("  StreamClose = 5,\n");
        out.push_str("  StreamCancel = 6,\n");
        out.push_str("  Ping = 7,\n");
        out.push_str("  Pong = 8,\n");
        out.push_str("  Error = 9,\n");
        out.push_str("  Credit = 10,\n");
        out.push_str("}\n\n");

        out.push_str("export interface FrameHeader {\n");
        out.push_str("  magic: number;\n");
        out.push_str("  version: number;\n");
        out.push_str("  frameType: FrameType;\n");
        out.push_str("  flags: number;\n");
        out.push_str("  streamId: number;\n");
        out.push_str("  methodId: number;\n");
        out.push_str("  payloadLen: number;\n");
        out.push_str("  checksum: number;\n");
        out.push_str("}\n\n");

        out.push_str("export interface Frame {\n");
        out.push_str("  header: FrameHeader;\n");
        out.push_str("  payload: Uint8Array;\n");
        out.push_str("}\n\n");

        // Generate Enums
        for e in &schema.enums {
            if let Some(doc) = &e.doc {
                out.push_str(&format!("/** {} */\n", doc));
            }
            out.push_str(&format!("export enum {} {{\n", e.name));
            for v in &e.variants {
                if let Some(doc) = &v.doc {
                    out.push_str(&format!("  /** {} */\n", doc));
                }
                out.push_str(&format!("  {} = {},\n", v.name, v.value));
            }
            out.push_str("}\n\n");
        }

        // Generate Struct Interfaces
        for s in &schema.structs {
            if let Some(doc) = &s.doc {
                out.push_str(&format!("/** {} */\n", doc));
            }
            out.push_str(&format!("export interface {} {{\n", s.name));
            for f in &s.fields {
                if let Some(doc) = &f.doc {
                    out.push_str(&format!("  /** {} */\n", doc));
                }
                let ts_type = self.map_type(&f.field_type);
                let optional = match f.modifier {
                    FieldModifier::Optional => "?",
                    FieldModifier::Required => "",
                };
                out.push_str(&format!("  {}{}: {};\n", f.name, optional, ts_type));
            }
            out.push_str("}\n\n");

            // Binary serialization helpers for each struct
            out.push_str(&format!("export namespace {} {{\n", s.name));
            out.push_str(&format!("  export function encode(msg: {}): Uint8Array {{\n", s.name));
            out.push_str("    const json = JSON.stringify(msg, (k, v) => typeof v === 'bigint' ? v.toString() : v);\n");
            out.push_str("    return new TextEncoder().encode(json);\n");
            out.push_str("  }\n\n");

            out.push_str(&format!("  export function decode(bytes: Uint8Array): {} {{\n", s.name));
            out.push_str("    const text = new TextDecoder().decode(bytes);\n");
            out.push_str(&format!("    return JSON.parse(text) as {};\n", s.name));
            out.push_str("  }\n");
            out.push_str("}\n\n");
        }

        // Generate Services & Clients
        for svc in &schema.services {
            if options.emit_client {
                out.push_str(&format!("/** Type-Safe Reactive Client for {} */\n", svc.name));
                out.push_str(&format!("export class {}Client {{\n", svc.name));
                out.push_str("  private transport: (frame: Frame) => Promise<Frame>;\n");
                out.push_str("  private streamTransport?: (frame: Frame) => AsyncIterable<Frame>;\n");
                out.push_str("  private nextStreamId = 1;\n\n");
                out.push_str("  constructor(\n");
                out.push_str("    transport: (frame: Frame) => Promise<Frame>,\n");
                out.push_str("    streamTransport?: (frame: Frame) => AsyncIterable<Frame>\n");
                out.push_str("  ) {\n");
                out.push_str("    this.transport = transport;\n");
                out.push_str("    this.streamTransport = streamTransport;\n");
                out.push_str("  }\n\n");

                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    let req_codec = match &m.request_type {
                        FieldType::Custom(name) => name.as_str(),
                        _ => "Object",
                    };
                    let resp_codec = match &m.response_type {
                        FieldType::Custom(name) => name.as_str(),
                        _ => "Object",
                    };

                    match m.streaming_mode {
                        StreamingMode::Unary => {
                            out.push_str(&format!("  async {}(req: {}): Promise<{}> {{\n", m.name, req_type, resp_type));
                            out.push_str(&format!("    const payload = {}.encode(req);\n", req_codec));
                            out.push_str("    const streamId = this.nextStreamId += 2;\n");
                            out.push_str(&format!("    const frame: Frame = {{\n      header: {{ magic: SYNAPSE_MAGIC, version: SYNAPSE_VERSION, frameType: FrameType.CallRequest, flags: 1, streamId, methodId: {}, payloadLen: payload.length, checksum: 0 }},\n      payload\n    }};\n", m.id));
                            out.push_str("    const respFrame = await this.transport(frame);\n");
                            out.push_str(&format!("    return {}.decode(respFrame.payload);\n", resp_codec));
                            out.push_str("  }\n\n");
                        }
                        StreamingMode::ServerStreaming => {
                            out.push_str(&format!("  async *{}(req: {}): AsyncIterable<{}> {{\n", m.name, req_type, resp_type));
                            out.push_str("    if (!this.streamTransport) throw new Error('Streaming transport not configured');\n");
                            out.push_str(&format!("    const payload = {}.encode(req);\n", req_codec));
                            out.push_str("    const streamId = this.nextStreamId += 2;\n");
                            out.push_str(&format!("    const frame: Frame = {{\n      header: {{ magic: SYNAPSE_MAGIC, version: SYNAPSE_VERSION, frameType: FrameType.CallRequest, flags: 0, streamId, methodId: {}, payloadLen: payload.length, checksum: 0 }},\n      payload\n    }};\n", m.id));
                            out.push_str("    for await (const resp of this.streamTransport(frame)) {\n");
                            out.push_str(&format!("      yield {}.decode(resp.payload);\n", resp_codec));
                            out.push_str("    }\n");
                            out.push_str("  }\n\n");
                        }
                        _ => {
                            out.push_str(&format!("  async *{}(reqStream: AsyncIterable<{}>): AsyncIterable<{}> {{\n", m.name, req_type, resp_type));
                            out.push_str("    if (!this.streamTransport) throw new Error('Bi-directional streaming transport not configured');\n");
                            out.push_str("    // Bidirectional multiplexed stream handler\n");
                            out.push_str("    for await (const req of reqStream) {\n");
                            out.push_str(&format!("      const payload = {}.encode(req);\n", req_codec));
                            out.push_str(&format!("      const frame: Frame = {{\n        header: {{ magic: SYNAPSE_MAGIC, version: SYNAPSE_VERSION, frameType: FrameType.StreamData, flags: 0, streamId: this.nextStreamId, methodId: {}, payloadLen: payload.length, checksum: 0 }},\n        payload\n      }};\n", m.id));
                            out.push_str("      for await (const resp of this.streamTransport(frame)) {\n");
                            out.push_str(&format!("        yield {}.decode(resp.payload);\n", resp_codec));
                            out.push_str("      }\n");
                            out.push_str("    }\n");
                            out.push_str("  }\n\n");
                        }
                    }
                }
                out.push_str("}\n\n");
            }

            if options.emit_server {
                out.push_str(&format!("/** Server Handler Interface for {} */\n", svc.name));
                out.push_str(&format!("export interface {}ServerHandler {{\n", svc.name));
                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    match m.streaming_mode {
                        StreamingMode::Unary => {
                            out.push_str(&format!("  {}(req: {}): Promise<{}>;\n", m.name, req_type, resp_type));
                        }
                        _ => {
                            out.push_str(&format!("  {}(req: {}): AsyncIterable<{}>;\n", m.name, req_type, resp_type));
                        }
                    }
                }
                out.push_str("}\n\n");

                out.push_str(&format!("export class {}Dispatcher {{\n", svc.name));
                out.push_str(&format!("  constructor(private handler: {}ServerHandler) {{}}\n\n", svc.name));
                out.push_str("  async dispatch(frame: Frame): Promise<Frame> {\n");
                out.push_str("    switch (frame.header.methodId) {\n");
                for m in &svc.methods {
                    let req_codec = match &m.request_type {
                        FieldType::Custom(name) => name.as_str(),
                        _ => "Object",
                    };
                    let resp_codec = match &m.response_type {
                        FieldType::Custom(name) => name.as_str(),
                        _ => "Object",
                    };
                    out.push_str(&format!("      case {}: {{\n", m.id));
                    out.push_str(&format!("        const req = {}.decode(frame.payload);\n", req_codec));
                    out.push_str(&format!("        const resp = await this.handler.{}(req);\n", m.name));
                    out.push_str(&format!("        const payload = {}.encode(resp);\n", resp_codec));
                    out.push_str("        return {\n");
                    out.push_str(&format!("          header: {{ magic: SYNAPSE_MAGIC, version: SYNAPSE_VERSION, frameType: FrameType.CallResponse, flags: 1, streamId: frame.header.streamId, methodId: {}, payloadLen: payload.length, checksum: 0 }},\n", m.id));
                    out.push_str("          payload\n");
                    out.push_str("        };\n");
                    out.push_str("      }\n");
                }
                out.push_str("      default:\n");
                out.push_str("        throw new Error(`Unknown method ID: ${frame.header.methodId}`);\n");
                out.push_str("    }\n");
                out.push_str("  }\n");
                out.push_str("}\n\n");
            }
        }

        let file_name = schema.namespace.as_ref()
            .map(|ns| format!("{}.ts", ns.parts.last().unwrap_or(&"generated".to_string())))
            .unwrap_or_else(|| "schema.ts".to_string());

        Ok(vec![GeneratedFile {
            relative_path: PathBuf::from("typescript").join(file_name),
            content: out,
        }])
    }
}
