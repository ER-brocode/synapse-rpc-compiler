use std::path::PathBuf;
use crate::error::Result;
use crate::parser::ast::*;
use crate::codegen::generator::{CodeGenerator, GeneratedFile, GeneratorOptions};

pub struct GoGenerator;

impl GoGenerator {
    pub fn new() -> Self {
        Self
    }

    fn map_primitive_type(prim: &PrimitiveType) -> &'static str {
        match prim {
            PrimitiveType::Bool => "bool",
            PrimitiveType::U8 => "uint8",
            PrimitiveType::U16 => "uint16",
            PrimitiveType::U32 => "uint32",
            PrimitiveType::U64 => "uint64",
            PrimitiveType::I8 => "int8",
            PrimitiveType::I16 => "int16",
            PrimitiveType::I32 => "int32",
            PrimitiveType::I64 => "int64",
            PrimitiveType::F32 => "float32",
            PrimitiveType::F64 => "float64",
            PrimitiveType::String => "string",
            PrimitiveType::Bytes => "[]byte",
            PrimitiveType::Uuid => "string",
            PrimitiveType::Timestamp => "uint64",
        }
    }

    fn map_type(&self, ty: &FieldType) -> String {
        match ty {
            FieldType::Primitive(p) => Self::map_primitive_type(p).to_string(),
            FieldType::List(inner) => format!("[]{}", self.map_type(inner)),
            FieldType::Map(k, v) => format!("map[{}]{}", self.map_type(k), self.map_type(v)),
            FieldType::Option(inner) => format!("*{}", self.map_type(inner)),
            FieldType::Result { ok, .. } => format!("*{}", self.map_type(ok)),
            FieldType::Custom(name) => format!("*{}", name),
        }
    }

    fn to_camel_case(s: &str) -> String {
        let mut result = String::new();
        let mut capitalize_next = true;
        for c in s.chars() {
            if c == '_' {
                capitalize_next = true;
            } else if capitalize_next {
                result.push(c.to_ascii_uppercase());
                capitalize_next = false;
            } else {
                result.push(c);
            }
        }
        result
    }
}

impl CodeGenerator for GoGenerator {
    fn generate(&self, schema: &Schema, options: &GeneratorOptions) -> Result<Vec<GeneratedFile>> {
        let mut out = String::new();

        let pkg_name = options.package_name.as_deref().unwrap_or("synapse");

        out.push_str("// Code generated by synapse-rpc-compiler. DO NOT EDIT.\n");
        out.push_str(&format!("package {}\n\n", pkg_name));

        out.push_str("import (\n");
        out.push_str("\t\"context\"\n");
        out.push_str("\t\"encoding/json\"\n");
        out.push_str("\t\"errors\"\n");
        out.push_str("\t\"fmt\"\n");
        out.push_str(")\n\n");

        out.push_str("const (\n");
        out.push_str("\tSynapseMagic   = 0x53594E50\n");
        out.push_str("\tSynapseVersion = 1\n");
        out.push_str(")\n\n");

        // Generate Enums
        for e in &schema.enums {
            if let Some(doc) = &e.doc {
                out.push_str(&format!("// {} {}\n", e.name, doc));
            }
            out.push_str(&format!("type {} int32\n\n", e.name));
            out.push_str("const (\n");
            for v in &e.variants {
                out.push_str(&format!("\t{}_{} {} = {}\n", e.name, v.name, e.name, v.value));
            }
            out.push_str(")\n\n");
        }

        // Generate Structs
        for s in &schema.structs {
            if let Some(doc) = &s.doc {
                out.push_str(&format!("// {} {}\n", s.name, doc));
            }
            out.push_str(&format!("type {} struct {{\n", s.name));
            for f in &s.fields {
                let go_field_name = Self::to_camel_case(&f.name);
                let go_type = self.map_type(&f.field_type);
                out.push_str(&format!("\t{} {} `json:\"{}\" synapse:\"id={}\"`\n", go_field_name, go_type, f.name, f.id));
            }
            out.push_str("}\n\n");

            // Binary Marshaller / Unmarshaller
            out.push_str(&format!("func (s *{}) MarshalSynapse() ([]byte, error) {{\n", s.name));
            out.push_str("\treturn json.Marshal(s)\n");
            out.push_str("}\n\n");

            out.push_str(&format!("func (s *{}) UnmarshalSynapse(data []byte) error {{\n", s.name));
            out.push_str("\treturn json.Unmarshal(data, s)\n");
            out.push_str("}\n\n");
        }

        // Generate Services
        for svc in &schema.services {
            if options.emit_client {
                out.push_str(&format!("// {}Client is the client API for {} service.\n", svc.name, svc.name));
                out.push_str(&format!("type {}Client interface {{\n", svc.name));
                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    out.push_str(&format!("\t{}(ctx context.Context, req {}) ({}, error)\n", m.name, req_type, resp_type));
                }
                out.push_str("}\n\n");

                out.push_str(&format!("type {}ClientImpl struct {{\n", svc.name.to_lowercase()));
                out.push_str("\ttransport func(ctx context.Context, methodID uint32, payload []byte) ([]byte, error)\n");
                out.push_str("}\n\n");

                out.push_str(&format!("func New{}Client(transport func(ctx context.Context, methodID uint32, payload []byte) ([]byte, error)) {}Client {{\n", svc.name, svc.name));
                out.push_str(&format!("\treturn &{}ClientImpl{{transport: transport}}\n", svc.name.to_lowercase()));
                out.push_str("}\n\n");

                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    let resp_struct = match &m.response_type {
                        FieldType::Custom(name) => name.as_str(),
                        _ => "struct{}",
                    };

                    out.push_str(&format!("func (c *{}ClientImpl) {}(ctx context.Context, req {}) ({}, error) {{\n", svc.name.to_lowercase(), m.name, req_type, resp_type));
                    out.push_str("\tpayload, err := json.Marshal(req)\n");
                    out.push_str("\tif err != nil {\n\t\treturn nil, err\n\t}\n");
                    out.push_str(&format!("\trespBytes, err := c.transport(ctx, {}, payload)\n", m.id));
                    out.push_str("\tif err != nil {\n\t\treturn nil, err\n\t}\n");
                    out.push_str(&format!("\tvar resp {}\n", resp_struct));
                    out.push_str("\tif err := json.Unmarshal(respBytes, &resp); err != nil {\n\t\treturn nil, err\n\t}\n");
                    out.push_str("\treturn &resp, nil\n");
                    out.push_str("}\n\n");
                }
            }

            if options.emit_server {
                out.push_str(&format!("// {}Server is the server API for {} service.\n", svc.name, svc.name));
                out.push_str(&format!("type {}Server interface {{\n", svc.name));
                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    out.push_str(&format!("\t{}(ctx context.Context, req {}) ({}, error)\n", m.name, req_type, resp_type));
                }
                out.push_str("}\n\n");

                out.push_str(&format!("type {}Dispatcher struct {{\n", svc.name));
                out.push_str(&format!("\tsrv {}Server\n", svc.name));
                out.push_str("}\n\n");

                out.push_str(&format!("func New{}Dispatcher(srv {}Server) *{}Dispatcher {{\n", svc.name, svc.name, svc.name));
                out.push_str(&format!("\treturn &{}Dispatcher{{srv: srv}}\n", svc.name));
                out.push_str("}\n\n");

                out.push_str(&format!("func (d *{}Dispatcher) Dispatch(ctx context.Context, methodID uint32, payload []byte) ([]byte, error) {{\n", svc.name));
                out.push_str("\tswitch methodID {\n");
                for m in &svc.methods {
                    let req_struct = match &m.request_type {
                        FieldType::Custom(name) => name.as_str(),
                        _ => "struct{}",
                    };
                    out.push_str(&format!("\tcase {}:\n", m.id));
                    out.push_str(&format!("\t\tvar req {}\n", req_struct));
                    out.push_str("\t\tif err := json.Unmarshal(payload, &req); err != nil {\n\t\t\treturn nil, err\n\t\t}\n");
                    out.push_str(&format!("\t\tresp, err := d.srv.{}(ctx, &req)\n", m.name));
                    out.push_str("\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n");
                    out.push_str("\t\treturn json.Marshal(resp)\n");
                }
                out.push_str("\tdefault:\n");
                out.push_str("\t\treturn nil, fmt.Errorf(\"unknown method ID: %d\", methodID)\n");
                out.push_str("\t}\n");
                out.push_str("}\n\n");
            }
        }

        let file_name = schema.namespace.as_ref()
            .map(|ns| format!("{}.go", ns.parts.last().unwrap_or(&"generated".to_string())))
            .unwrap_or_else(|| "schema.go".to_string());

        Ok(vec![GeneratedFile {
            relative_path: PathBuf::from("go").join(file_name),
            content: out,
        }])
    }
}
