use std::path::PathBuf;
use crate::error::Result;
use crate::parser::ast::*;
use crate::codegen::generator::{CodeGenerator, GeneratedFile, GeneratorOptions};

pub struct RustGenerator;

impl RustGenerator {
    pub fn new() -> Self {
        Self
    }

    fn map_primitive_type(prim: &PrimitiveType) -> &'static str {
        match prim {
            PrimitiveType::Bool => "bool",
            PrimitiveType::U8 => "u8",
            PrimitiveType::U16 => "u16",
            PrimitiveType::U32 => "u32",
            PrimitiveType::U64 => "u64",
            PrimitiveType::I8 => "i8",
            PrimitiveType::I16 => "i16",
            PrimitiveType::I32 => "i32",
            PrimitiveType::I64 => "i64",
            PrimitiveType::F32 => "f32",
            PrimitiveType::F64 => "f64",
            PrimitiveType::String => "String",
            PrimitiveType::Bytes => "Vec<u8>",
            PrimitiveType::Uuid => "String",
            PrimitiveType::Timestamp => "u64",
        }
    }

    fn map_type(&self, ty: &FieldType) -> String {
        match ty {
            FieldType::Primitive(p) => Self::map_primitive_type(p).to_string(),
            FieldType::List(inner) => format!("Vec<{}>", self.map_type(inner)),
            FieldType::Map(k, v) => format!("std::collections::HashMap<{}, {}>", self.map_type(k), self.map_type(v)),
            FieldType::Option(inner) => format!("Option<{}>", self.map_type(inner)),
            FieldType::Result { ok, err } => format!("std::result::Result<{}, {}>", self.map_type(ok), self.map_type(err)),
            FieldType::Custom(name) => name.clone(),
        }
    }
}

impl CodeGenerator for RustGenerator {
    fn generate(&self, schema: &Schema, options: &GeneratorOptions) -> Result<Vec<GeneratedFile>> {
        let mut out = String::new();

        out.push_str("// Code generated by synapse-rpc-compiler. DO NOT EDIT.\n");
        out.push_str("#![allow(unused_imports, dead_code, clippy::all)]\n\n");
        out.push_str("use std::sync::Arc;\n");
        out.push_str("use serde::{Serialize, Deserialize};\n");
        out.push_str("use synapse_compiler::error::{Result, SynapseError};\n");
        out.push_str("use synapse_compiler::runtime::*;\n\n");

        if let Some(ns) = &schema.namespace {
            out.push_str(&format!("// Namespace: {}\n\n", ns.to_string()));
        }

        // Generate Enums
        for e in &schema.enums {
            if let Some(doc) = &e.doc {
                out.push_str(&format!("/// {}\n", doc));
            }
            out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]\n");
            out.push_str("#[repr(i32)]\n");
            out.push_str(&format!("pub enum {} {{\n", e.name));
            for v in &e.variants {
                if let Some(doc) = &v.doc {
                    out.push_str(&format!("    /// {}\n", doc));
                }
                out.push_str(&format!("    {} = {},\n", v.name, v.value));
            }
            out.push_str("}\n\n");

            // Enum from_i32 and to_i32
            out.push_str(&format!("impl {} {{\n", e.name));
            out.push_str("    pub fn from_i32(val: i32) -> Option<Self> {\n");
            out.push_str("        match val {\n");
            for v in &e.variants {
                out.push_str(&format!("            {} => Some(Self::{}),\n", v.value, v.name));
            }
            out.push_str("            _ => None,\n");
            out.push_str("        }\n");
            out.push_str("    }\n\n");
            out.push_str("    pub fn to_i32(self) -> i32 {\n");
            out.push_str("        self as i32\n");
            out.push_str("    }\n");
            out.push_str("}\n\n");

            // Codec for Enum
            out.push_str(&format!("impl SynapseCodec for {} {{\n", e.name));
            out.push_str("    fn encode(&self, encoder: &mut SynapseEncoder) -> Result<()> {\n");
            out.push_str("        encoder.write_i32(1, self.to_i32());\n");
            out.push_str("        Ok(())\n");
            out.push_str("    }\n\n");
            out.push_str("    fn decode(decoder: &mut SynapseDecoder) -> Result<Self> {\n");
            out.push_str("        let val = decoder.read_i32()?;\n");
            out.push_str(&format!("        Self::from_i32(val).ok_or_else(|| SynapseError::CodecError {{\n            message: format!(\"Unknown variant {{}} for {}\", val),\n        }})\n", e.name));
            out.push_str("    }\n");
            out.push_str("}\n\n");
        }

        // Generate Structs
        for s in &schema.structs {
            if let Some(doc) = &s.doc {
                out.push_str(&format!("/// {}\n", doc));
            }
            out.push_str("#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n");
            out.push_str(&format!("pub struct {} {{\n", s.name));
            for f in &s.fields {
                if let Some(doc) = &f.doc {
                    out.push_str(&format!("    /// {}\n", doc));
                }
                let rust_type = self.map_type(&f.field_type);
                out.push_str(&format!("    pub {}: {},\n", f.name, rust_type));
            }
            out.push_str("}\n\n");

            // Implement SynapseCodec
            out.push_str(&format!("impl SynapseCodec for {} {{\n", s.name));
            out.push_str("    fn encode(&self, encoder: &mut SynapseEncoder) -> Result<()> {\n");
            for f in &s.fields {
                match &f.field_type {
                    FieldType::Primitive(p) => match p {
                        PrimitiveType::Bool => out.push_str(&format!("        encoder.write_bool({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::U8 => out.push_str(&format!("        encoder.write_u8({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::U16 => out.push_str(&format!("        encoder.write_u16({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::U32 => out.push_str(&format!("        encoder.write_u32({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::U64 => out.push_str(&format!("        encoder.write_u64({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::I8 => out.push_str(&format!("        encoder.write_i8({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::I16 => out.push_str(&format!("        encoder.write_i16({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::I32 => out.push_str(&format!("        encoder.write_i32({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::I64 => out.push_str(&format!("        encoder.write_i64({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::F32 => out.push_str(&format!("        encoder.write_f32({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::F64 => out.push_str(&format!("        encoder.write_f64({}, self.{});\n", f.id, f.name)),
                        PrimitiveType::String | PrimitiveType::Uuid => out.push_str(&format!("        encoder.write_string({}, &self.{});\n", f.id, f.name)),
                        PrimitiveType::Bytes => out.push_str(&format!("        encoder.write_bytes({}, &self.{});\n", f.id, f.name)),
                        PrimitiveType::Timestamp => out.push_str(&format!("        encoder.write_u64({}, self.{});\n", f.id, f.name)),
                    },
                    FieldType::Custom(_) => {
                        out.push_str(&format!("        let mut nested = SynapseEncoder::new();\n"));
                        out.push_str(&format!("        self.{}.encode(&mut nested)?;\n", f.name));
                        out.push_str(&format!("        encoder.write_nested_message({}, &nested);\n", f.id));
                    }
                    FieldType::Option(_) => {
                        out.push_str(&format!("        if let Some(ref val) = self.{} {{\n", f.name));
                        out.push_str(&format!("            let mut nested = SynapseEncoder::new();\n"));
                        out.push_str("            val.encode(&mut nested)?;\n");
                        out.push_str(&format!("            encoder.write_nested_message({}, &nested);\n", f.id));
                        out.push_str("        }\n");
                    }
                    _ => {
                        // Other compound types serialized via json fallback or nested encoder
                        out.push_str(&format!("        let json_bytes = serde_json::to_vec(&self.{})?;\n", f.name));
                        out.push_str(&format!("        encoder.write_bytes({}, &json_bytes);\n", f.id));
                    }
                }
            }
            out.push_str("        Ok(())\n");
            out.push_str("    }\n\n");

            // Decode
            out.push_str("    fn decode(decoder: &mut SynapseDecoder) -> Result<Self> {\n");
            for f in &s.fields {
                let rust_type = self.map_type(&f.field_type);
                out.push_str(&format!("        let mut val_{}: Option<{}> = None;\n", f.name, rust_type));
            }
            out.push_str("        while let Some((field_id, wire_type)) = decoder.read_tag()? {\n");
            out.push_str("            match field_id {\n");
            for f in &s.fields {
                out.push_str(&format!("                {} => {{\n", f.id));
                match &f.field_type {
                    FieldType::Primitive(p) => match p {
                        PrimitiveType::Bool => out.push_str(&format!("                    val_{} = Some(decoder.read_bool()?);\n", f.name)),
                        PrimitiveType::U8 => out.push_str(&format!("                    val_{} = Some(decoder.read_u8()?);\n", f.name)),
                        PrimitiveType::U16 => out.push_str(&format!("                    val_{} = Some(decoder.read_u16()?);\n", f.name)),
                        PrimitiveType::U32 => out.push_str(&format!("                    val_{} = Some(decoder.read_u32()?);\n", f.name)),
                        PrimitiveType::U64 => out.push_str(&format!("                    val_{} = Some(decoder.read_u64()?);\n", f.name)),
                        PrimitiveType::I8 => out.push_str(&format!("                    val_{} = Some(decoder.read_i8()?);\n", f.name)),
                        PrimitiveType::I16 => out.push_str(&format!("                    val_{} = Some(decoder.read_i16()?);\n", f.name)),
                        PrimitiveType::I32 => out.push_str(&format!("                    val_{} = Some(decoder.read_i32()?);\n", f.name)),
                        PrimitiveType::I64 => out.push_str(&format!("                    val_{} = Some(decoder.read_i64()?);\n", f.name)),
                        PrimitiveType::F32 => out.push_str(&format!("                    val_{} = Some(decoder.read_f32()?);\n", f.name)),
                        PrimitiveType::F64 => out.push_str(&format!("                    val_{} = Some(decoder.read_f64()?);\n", f.name)),
                        PrimitiveType::String | PrimitiveType::Uuid => out.push_str(&format!("                    val_{} = Some(decoder.read_string()?);\n", f.name)),
                        PrimitiveType::Bytes => out.push_str(&format!("                    val_{} = Some(decoder.read_bytes()?);\n", f.name)),
                        PrimitiveType::Timestamp => out.push_str(&format!("                    val_{} = Some(decoder.read_u64()?);\n", f.name)),
                    },
                    FieldType::Custom(custom) => {
                        out.push_str(&format!("                    let mut nested = decoder.read_nested_decoder()?;\n"));
                        out.push_str(&format!("                    val_{} = Some({}::decode(&mut nested)?);\n", f.name, custom));
                    }
                    _ => {
                        let rust_type = self.map_type(&f.field_type);
                        out.push_str(&format!("                    let bytes = decoder.read_bytes()?;\n"));
                        out.push_str(&format!("                    let parsed: {} = serde_json::from_slice(&bytes)?;\n", rust_type));
                        out.push_str(&format!("                    val_{} = Some(parsed);\n", f.name));
                    }
                }
                out.push_str("                }\n");
            }
            out.push_str("                _ => decoder.skip_field(wire_type)?,\n");
            out.push_str("            }\n");
            out.push_str("        }\n\n");

            out.push_str(&format!("        Ok({} {{\n", s.name));
            for f in &s.fields {
                match &f.field_type {
                    FieldType::Option(_) => {
                        out.push_str(&format!("            {}: val_{},\n", f.name, f.name));
                    }
                    _ => {
                        out.push_str(&format!("            {}: val_{}.unwrap_or_default(),\n", f.name, f.name));
                    }
                }
            }
            out.push_str("        })\n");
            out.push_str("    }\n");
            out.push_str("}\n\n");
        }

        // Generate Services
        for svc in &schema.services {
            if options.emit_server {
                out.push_str(&format!("pub trait {}Server: Send + Sync {{\n", svc.name));
                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    out.push_str(&format!("    fn {}(&self, req: {}) -> Result<{}>;\n", m.name, req_type, resp_type));
                }
                out.push_str("}\n\n");

                out.push_str(&format!("pub fn register_{}(server: &mut SynapseServer, handler: Arc<dyn {}Server>) {{\n", svc.name.to_lowercase(), svc.name));
                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    out.push_str(&format!("    {{\n"));
                    out.push_str(&format!("        let h = Arc::clone(&handler);\n"));
                    out.push_str(&format!("        server.register_typed_handler({}, move |req: {}| h.{}(req));\n", m.id, req_type, m.name));
                    out.push_str("    }\n");
                }
                out.push_str("}\n\n");
            }

            if options.emit_client {
                out.push_str(&format!("pub struct {}Client {{\n", svc.name));
                out.push_str("    client: SynapseClient,\n");
                out.push_str("}\n\n");

                out.push_str(&format!("impl {}Client {{\n", svc.name));
                out.push_str("    pub fn new() -> Self {\n");
                out.push_str("        Self { client: SynapseClient::new() }\n");
                out.push_str("    }\n\n");
                for m in &svc.methods {
                    let req_type = self.map_type(&m.request_type);
                    let resp_type = self.map_type(&m.response_type);
                    out.push_str(&format!("    pub fn {}(&mut self, req: &{}) -> Result<(u32, Frame)> {{\n", m.name, req_type));
                    out.push_str(&format!("        self.client.create_unary_request({}, req)\n", m.id));
                    out.push_str("    }\n\n");
                    out.push_str(&format!("    pub fn parse_{}_response(&mut self, frame: &Frame) -> Result<{}> {{\n", m.name, resp_type));
                    out.push_str("        self.client.parse_unary_response(frame)\n");
                    out.push_str("    }\n\n");
                }
                out.push_str("}\n\n");
            }
        }

        let file_name = schema.namespace.as_ref()
            .map(|ns| format!("{}.rs", ns.parts.last().unwrap_or(&"generated".to_string())))
            .unwrap_or_else(|| "schema.rs".to_string());

        Ok(vec![GeneratedFile {
            relative_path: PathBuf::from("rust").join(file_name),
            content: out,
        }])
    }
}
